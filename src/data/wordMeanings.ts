export function getWordMeaningsBySurahId(surahId: number): SurahWordMeanings | undefined {
  return JUZ_AMMA_WORD_MEANINGS.find((s) => s.surahId === surahId);
}

export function searchWordMeanings(query: string, removeDiacriticsFn: (text: string) => string): { surahId: number; surahName: string; word: WordMeaning }[] {
  if (!query || query.trim().length === 0) return [];
  const cleanQ = removeDiacriticsFn(query.trim().toLowerCase());
  const results: { surahId: number; surahName: string; word: WordMeaning }[] = [];

  for (const item of JUZ_AMMA_WORD_MEANINGS) {
    for (const w of item.words) {
      const cleanWord = removeDiacriticsFn(w.word.toLowerCase());
      const cleanMeaning = removeDiacriticsFn(w.meaning.toLowerCase());
      if (cleanWord.includes(cleanQ) || cleanMeaning.includes(cleanQ)) {
        results.push({
          surahId: item.surahId,
          surahName: item.surahName,
          word: w
        });
      }
    }
  }

  return results;
}
